def test_cases():
    bad = [(src, normalize(src), want) for src, want in CASES if normalize(src) != want]
    assert not bad, "\n".join(f"{s!r}: got {g!r}, want {w!r}" for s, g, w in bad)


def test_numbers():
    assert sino(0) == "영"
    assert sino(10) == "십" and sino(11) == "십일" and sino(110) == "백십"
    assert sino(10000) == "만" and sino(11000) == "만천" and sino(100000000) == "일억"
    assert sino(2026) == "이천이십육" and sino(968000000000) == "구천육백팔십억"
    assert native(20) == "스무" and native(20, attrib=False) == "스물" and native(4) == "네" and native(100) == "백"


def test_extra_words():
    assert normalize("Foobar 출시", words={"Foobar": "푸바"}) == "푸바 출시"
    assert normalize("Claude Opus 4.5", words={"Opus 4.5": "오퍼스 사 점 오"}) == "클로드 오퍼스 사 점 오"


def test_unknown_warn():
    w = []
    normalize("Zorblax 공개", warn=w)
    assert w == ["Zorblax"]


def test_compare():
    # 받아쓰기가 아라비아 숫자로 적으면 어떤 읽기든 맞음
    assert compare("2주 만에 3개", "2주 만에 3개")["ok"]
    # 한글로 적힌 잘못 읽기는 잡는다 (이 주 → 두 주)
    r = compare("2주 만에 끝났다", "두 주 만에 끝났다")
    assert not r["ok"] and r["diffs"]
    # 영어로 받아써도 사전으로 맞춘다
    assert compare("OpenAI가 GPT-5를 공개", "오픈AI가 GPT-5를 공개")["ok"]
    assert compare("9,680억 달러", "9680억 달러")["ok"]
    assert not compare("앤트로픽이 상장", "엔트로피가 상장")["ok"]


